"""Hand-written serializers for the payments API actions.

Only the ``checkout`` / ``refund`` action payloads live here — the resource
serializers for ``Payment`` and ``Refund`` are generated by
:func:`karni.api.serializers.build_serializer` from the models' ``APIMeta``
(see :mod:`karni_payments.viewsets`). These explicit input/output
serializers feed ``@extend_schema`` so the OpenAPI schema (and with it
@karni/ui's typed client) knows the action shapes.

Override / escape hatch: subclass the viewset and swap the serializer in an
overridden action; these classes are plain DRF serializers.
"""

from __future__ import annotations

from decimal import Decimal

from rest_framework import serializers

from karni_payments.models import Refund

__all__ = [
    "CheckoutInputSerializer",
    "CheckoutOutputSerializer",
    "RefundInputSerializer",
    "RefundSerializer",
]


class CheckoutInputSerializer(serializers.Serializer):
    """Input of ``POST /api/payments/checkout/``.

    The amount is transport, not authority: the server-side
    ``KARNI_PAYMENTS_CHECKOUT_VALIDATOR`` decides whether it is acceptable
    (amendment G2 — never trust client amounts).
    """

    amount = serializers.DecimalField(max_digits=12, decimal_places=2, min_value=Decimal("0.01"))
    currency = serializers.CharField(max_length=3, required=False)
    metadata = serializers.JSONField(required=False)
    success_url = serializers.URLField(max_length=2000)
    cancel_url = serializers.URLField(max_length=2000)


class CheckoutOutputSerializer(serializers.Serializer):
    """Output of the checkout action: redirect the customer to ``url``."""

    payment_id = serializers.UUIDField(read_only=True)
    session_id = serializers.CharField(read_only=True)
    url = serializers.URLField(read_only=True)


class RefundInputSerializer(serializers.Serializer):
    """Input of ``POST /api/payments/{id}/refund/`` (empty body → full remainder)."""

    amount = serializers.DecimalField(
        max_digits=12, decimal_places=2, min_value=Decimal("0.01"), required=False
    )
    reason = serializers.CharField(max_length=255, required=False, allow_blank=True, default="")


class RefundSerializer(serializers.ModelSerializer):
    """Read-only representation of a refund (the refund action's response)."""

    class Meta:
        model = Refund
        fields = [
            "id",
            "payment",
            "amount",
            "status",
            "provider_refund_id",
            "reason",
            "created_at",
            "updated_at",
        ]
        read_only_fields = fields
