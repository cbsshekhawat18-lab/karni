// ESLint flat config (ESLint >= 9) for the frontend.
//
// The Karni enforcement rules live in @karni/ui's bundled plugin and activate
// fully once @karni/ui is installed: karni/no-raw-elements (compose
// ResourceTable/ResourceForm/Input instead of raw elements),
// karni/max-page-lines (pages cap at 50 physical lines),
// karni/no-deep-imports (never import @karni/ui/dist or /src),
// karni/no-direct-http (fetch/axios only under src/api/), plus required
// reasons on every eslint-disable comment and errors on unused disables.
//
// Until @karni/ui is installed, this file falls back to a minimal TypeScript
// config so a fresh scaffold still lints — the fallback warns instead of
// silently skipping, and the karni/* rules land the moment @karni/ui is
// available. Like the backend's KARNI_SRC pattern, @karni/ui may not be
// published yet: it is an optionalDependency, so `npm install` skips it while
// unresolvable and picks it up once published (or install a local checkout:
// `npm install /path/to/Karni/packages/karni-ui`).
import js from "@eslint/js";
import globals from "globals";
import tseslint from "typescript-eslint";

let karniRecommended = [];
try {
    const karni = await import("@karni/ui/eslint-plugin");
    karniRecommended = karni.default.configs.recommended;
} catch {
    console.warn(
        "[eslint] @karni/ui is not installed - the karni/* enforcement rules are off until it is.",
    );
}

export default tseslint.config(
    // src/api/ is generated by `karni types` (and is the allowed home of raw
    // HTTP) — lint what you write, not what Karni generates.
    { ignores: ["dist/", "node_modules/", "src/api/**"] },
    js.configs.recommended,
    ...tseslint.configs.recommended,
    ...karniRecommended,
    {
        files: ["**/*.ts", "**/*.tsx"],
        languageOptions: {
            globals: { ...globals.browser },
            parserOptions: { ecmaFeatures: { jsx: true } },
        },
    },
    {
        files: ["eslint.config.js", "vite.config.ts"],
        languageOptions: { globals: { ...globals.node } },
    },
);
