"""Experimental. ``karni recipes list|show --json``: its output, and the JSON Schema published for it.

The output is ``{version, request, threshold, recipes, blank, next, problems}``.
``karni recipes list`` lists every recipe, ``--match`` the best few for a
request with their scores, and ``karni recipes show <name>`` one recipe with
its spec. The MCP tool ``recipes`` returns the same. The schema is published
as ``docs/assets/karni-recipes.schema.json`` (regenerate it with
``python -m karni_cli.recipes.output > docs/assets/karni-recipes.schema.json``),
and ``version`` moves only for a breaking change of the output.
"""

from __future__ import annotations

import json
from typing import Any, Final, Literal

from pydantic import BaseModel, ConfigDict, Field

from karni_cli import recipes as recipes_mod
from karni_cli.recipes import BLANK, Loaded, Match, Recipe

__all__ = [
    "RECIPES_SCHEMA_URL",
    "RECIPES_VERSION",
    "checked",
    "json_schema",
    "listing",
    "matched",
    "shown",
]

#: Experimental. The version of the ``--json`` output. It moves only for a breaking change.
RECIPES_VERSION: Final = 1
#: Experimental. Where the JSON Schema of ``karni recipes list|show --json`` is published.
RECIPES_SCHEMA_URL: Final = (
    "https://cbsshekhawat18-lab.github.io/karni/assets/karni-recipes.schema.json"
)


class _Out(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class _RecipeOut(_Out):
    """One recipe."""

    name: str = Field(description="The recipe's name: karni recipes show <name>.")
    title: str = Field(description="A short human name.")
    purpose: str = Field(description="What the app does, in one line.")
    use_when: list[str] = Field(description="What someone asks for when it fits.")
    usually_changed: list[str] = Field(description="What people usually change after starting.")
    source: str = Field(description="built in, or the entry point (karni.recipes) it comes from.")
    files: list[str] = Field(
        description="Its own domain code, seeds and tests, at the paths they take in the project."
    )
    spec: str | None = Field(description="Its karni.yaml (karni recipes show). null in a list.")
    score: int | None = Field(
        description="With --match: 2 for each word of the request a use_when phrase has, 1 for "
        "each one only the purpose has. null without --match."
    )
    matched: list[str] = Field(description="With --match: the words that scored.")


class _BlankOut(_Out):
    """The blank start: where an app starts when no recipe fits."""

    name: Literal["blank"] = Field(description="blank: karni recipes show blank.")
    spec: str = Field(description="karni.yaml with the version and the app's name, nothing else.")


class _RecipesOut(_Out):
    """Experimental. The output of karni recipes list|show --json."""

    version: Literal[1] = Field(description="The version of this output: 1.")
    request: str | None = Field(description="The request given to --match. null otherwise.")
    threshold: int = Field(description="The lowest score --match returns.")
    recipes: list[_RecipeOut] = Field(
        description="Every recipe, the best few for the request (highest score first), or the "
        "one shown. Empty when none matches."
    )
    blank: _BlankOut = Field(description="The blank start.")
    next: str = Field(description="What to do next.")
    problems: list[str] = Field(
        description="Recipes left out because they cannot be used (C421), each with the reason."
    )


def json_schema() -> dict[str, Any]:
    """Experimental. The JSON Schema of ``karni recipes list|show --json``."""
    from karni_cli.spec.schema import _tidy

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": RECIPES_SCHEMA_URL,
        "title": "karni recipes list|show --json",
        "description": (
            "Experimental. The recipes a new app can start from, and the blank start. "
            "Generated by python -m karni_cli.recipes.output. Never edit it by hand."
        ),
        **_tidy(_RecipesOut.model_json_schema()),
    }


def checked(data: dict[str, Any]) -> dict[str, Any]:
    """Experimental. ``data`` checked against the published schema's models (raises on a mismatch)."""
    return _RecipesOut.model_validate(data).model_dump(mode="json")


def _blank(app_name: str) -> dict[str, Any]:
    return {"name": BLANK, "spec": recipes_mod.blank_spec(app_name)}


def _out(
    loaded: Loaded,
    entries: list[dict[str, Any]],
    *,
    request: str | None,
    app_name: str,
    next_: str,
) -> dict[str, Any]:
    return checked(
        {
            "version": RECIPES_VERSION,
            "request": request,
            "threshold": recipes_mod.MATCH_THRESHOLD,
            "recipes": entries,
            "blank": _blank(app_name),
            "next": next_,
            "problems": list(loaded.problems),
        }
    )


def _entry(recipe: Recipe, *, spec: bool = False, found: Match | None = None) -> dict[str, Any]:
    return {
        **recipe.to_dict(spec=spec),
        "score": found.score if found else None,
        "matched": list(found.matched) if found else [],
    }


#: What to do with the blank start, in every output that names it.
_BLANK_NEXT: Final = (
    "start karni.yaml from the blank start (karni recipes show blank) and write in it what "
    "the request asks for"
)


def listing(loaded: Loaded, *, app_name: str) -> dict[str, Any]:
    """Experimental. Every recipe, then the blank start."""
    entries = [_entry(recipe) for recipe in loaded.recipes.values()]
    next_ = (
        'karni recipes list --match "<the request>" names the closest, or '
        if entries
        else "no recipe is installed: "
    ) + _BLANK_NEXT
    return _out(loaded, entries, request=None, app_name=app_name, next_=next_)


def matched(loaded: Loaded, request: str, *, app_name: str) -> dict[str, Any]:
    """Experimental. The best few recipes for ``request``, with their scores."""
    found = recipes_mod.match(loaded.recipes.values(), request)
    entries = [_entry(item.recipe, found=item) for item in found]
    if found:
        best = found[0].recipe.name
        next_ = (
            f"start karni.yaml from the closest recipe that fits (karni recipes show {best} "
            "prints its spec), or, when none does, " + _BLANK_NEXT
        )
    else:
        next_ = "no recipe matches: " + _BLANK_NEXT
    return _out(loaded, entries, request=request, app_name=app_name, next_=next_)


def shown(loaded: Loaded, name: str, *, app_name: str) -> dict[str, Any]:
    """Experimental. One recipe with its spec (``blank``: the blank start alone).

    :raises CliError: ``C420`` when there is no such recipe, ``C421`` when it
        cannot be used (:meth:`Loaded.require`).
    """
    recipe = loaded.require(name)
    if recipe is None:
        next_ = "write it to karni.yaml, add what the request asks for, then karni plan --questions"
        return _out(loaded, [], request=None, app_name=app_name, next_=next_)
    next_ = (
        "write its spec to karni.yaml, change what the request asks for, then karni plan "
        "--questions"
    )
    return _out(loaded, [_entry(recipe, spec=True)], request=None, app_name=app_name, next_=next_)


if __name__ == "__main__":  # pragma: no cover - python -m karni_cli.recipes.output
    print(json.dumps(json_schema(), indent=2, sort_keys=False))
