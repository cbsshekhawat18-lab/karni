"""The agent instructions, generated from data (``karni rules sync``).

Inputs, and nothing else: the adapter registry (``agent_adapters.toml``), the
rule/procedure data (:mod:`karni_cli.agent_data`), the project's
``karni.rules.py`` adapter overrides, the module guidance recorded by
``karni add`` under ``.karni/modules/``, the project name in
``pyproject.toml`` and the project's kind (:mod:`karni_cli.kinds`: ``kind``
under ``[tool.karni]``, and whether ``frontend/`` holds a staff app). Same
inputs, same bytes, which is what makes
``karni rules sync --check`` a reliable CI staleness gate.

Safety: sync only overwrites files that carry the generated marker. A
hand-written file in an adapter's place is reported, never clobbered, unless
``--force`` (which backs it up under ``.karni/backup/`` first).

AGENTS.md is the one agent file Karni writes. The registry's other entries
(one tool's instruction file or command folder each) are deprecated since
0.5.0 and leave in 1.0: sync writes them only where a project already has
them (a generated file at the entry's path, or a generated file in its
command folder), keeps those up to date, and reports them with code C860
(:data:`DEPRECATED_CODE`, :func:`deprecation_warning`).
"""

from __future__ import annotations

import json
import re
import shutil
import tomllib
from collections.abc import Collection
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path
from typing import Any

from karni_cli.agent_data import AgentData
from karni_cli.kinds import ProjectKind, project_kind
from karni_cli.project import CliError

GENERATED_MARK = "Generated by `karni rules sync`"
MARKER_LINE = (
    f"<!-- {GENERATED_MARK} from Karni's rule registry. Do not edit: "
    "project rules go in karni.rules.py. -->"
)
MODULES_DIR = Path(".karni") / "modules"
BACKUP_DIR = Path(".karni") / "backup"
_TEMPLATES = ("instructions", "import", "command")
#: The procedure that builds an app from a one-line request (rule K311).
NEW_APP = "new-app"
_YAML_PLAIN = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9 _./()-]*$")
#: The code for the deprecated per-tool files (``karni rules sync``, ``karni doctor``).
DEPRECATED_CODE = "C860"


@dataclass(frozen=True)
class Adapter:
    id: str
    tool: str
    path: str
    template: str
    modules: bool = False
    frontmatter: dict[str, Any] = field(default_factory=dict)
    imports: str | None = None
    note: str = ""
    #: Deprecated since 0.5.0: written only where the project already has it.
    deprecated: bool = False


@dataclass(frozen=True)
class CommandTarget:
    id: str
    tool: str
    dir: str
    suffix: str
    arguments: str
    frontmatter: tuple[str, ...] = ()
    agent: str | None = None
    #: Deprecated since 0.5.0: written only where the project already has it.
    deprecated: bool = False


@dataclass(frozen=True)
class Registry:
    adapters: tuple[Adapter, ...]
    commands: tuple[CommandTarget, ...]
    max_lines: int

    def ids(self) -> set[str]:
        return {a.id for a in self.adapters} | {c.id for c in self.commands}


def load_registry(path: Path | None = None) -> Registry:
    if path is None:
        text = (resources.files("karni_cli") / "agent_adapters.toml").read_text(encoding="utf-8")
    else:
        text = path.read_text(encoding="utf-8")
    data = tomllib.loads(text)
    adapters = tuple(
        Adapter(
            id=entry["id"],
            tool=entry.get("tool", entry["id"]),
            path=entry["path"],
            template=entry["template"],
            modules=bool(entry.get("modules", False)),
            frontmatter=dict(entry.get("frontmatter", {})),
            imports=entry.get("import"),
            note=entry.get("note", ""),
            deprecated=bool(entry.get("deprecated", False)),
        )
        for entry in data.get("adapter", [])
    )
    commands = tuple(
        CommandTarget(
            id=entry["id"],
            tool=entry.get("tool", entry["id"]),
            dir=entry["dir"],
            suffix=entry["suffix"],
            arguments=entry["arguments"],
            frontmatter=tuple(entry.get("frontmatter", [])),
            agent=entry.get("agent"),
            deprecated=bool(entry.get("deprecated", False)),
        )
        for entry in data.get("commands", [])
    )
    for adapter in adapters:
        if adapter.template not in _TEMPLATES:
            raise CliError(
                f"agent adapter {adapter.id}: unknown template {adapter.template!r}", code="C205"
            )
    return Registry(adapters, commands, int(data.get("defaults", {}).get("max_lines", 100)))


def apply_overrides(registry: Registry, overrides: dict[str, Any]) -> Registry:
    """Honour ``ADAPTERS = {"disable": [...], "paths": {...}}`` from karni.rules.py."""
    disable = set(overrides.get("disable", []))
    paths: dict[str, str] = dict(overrides.get("paths", {}))
    unknown = (disable | set(paths)) - registry.ids()
    if unknown:
        raise CliError(
            f"karni.rules.py ADAPTERS names unknown adapter id(s): {', '.join(sorted(unknown))} "
            f"(known: {', '.join(sorted(registry.ids()))}).",
            code="C205",
        )
    adapters = tuple(
        Adapter(**{**a.__dict__, "path": paths.get(a.id, a.path)})
        for a in registry.adapters
        if a.id not in disable
    )
    commands = tuple(
        CommandTarget(**{**c.__dict__, "dir": paths.get(c.id, c.dir)})
        for c in registry.commands
        if c.id not in disable
    )
    return Registry(adapters, commands, registry.max_lines)


# inputs from the project


def module_fragments(project: Path) -> dict[str, str]:
    """Module guidance recorded by ``karni add``: ``{module: fragment}``, sorted."""
    directory = project / MODULES_DIR
    if not directory.is_dir():
        return {}
    return {
        path.stem: path.read_text(encoding="utf-8").strip()
        for path in sorted(directory.glob("*.md"))
    }


def project_title(project: Path) -> str:
    pyproject = project / "pyproject.toml"
    if pyproject.is_file():
        try:
            name = tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]["name"]
            if isinstance(name, str) and name.strip():
                return name.strip()
        except (tomllib.TOMLDecodeError, KeyError, TypeError):
            pass
    return project.resolve().name


# rendering


def _yaml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None or value == "":
        return ""
    text = str(value)
    return text if _YAML_PLAIN.match(text) else json.dumps(text, ensure_ascii=False)


def _frontmatter(values: dict[str, Any]) -> list[str]:
    if not values:
        return []
    lines = ["---"]
    for key, value in values.items():
        rendered = _yaml_value(value)
        lines.append(f"{key}: {rendered}" if rendered else f"{key}:")
    lines.append("---")
    return lines


def instructions_body(
    title: str, data: AgentData, note: str = "", kind: ProjectKind | None = None
) -> list[str]:
    """The shared body: the project's kind and stack, then context and rules before any work.

    Without ``kind`` (no project to read it from), a line says where app screens
    and a public site go instead.
    """
    lines = [
        MARKER_LINE,
        f"# {title}: agent instructions",
        "",
        "This is a Karni project. Karni already implements everything generic, so you write",
        "only domain code.",
        "",
    ]
    if kind is not None:
        lines += [*kind.agent_lines(), ""]
    lines += [
        "Before any work, run these two commands and follow what they return:",
        "",
        "1. `karni context` prints the live inventory: apps, models, viewsets, UI components,",
        "   hooks, pages, and every Karni module and built-in feature with whether the",
        "   project has it (details: `karni modules show <name>`).",
        "2. `karni rules` prints the conventions, each with a stable code (K###, or P### for",
        "   the project's own).",
        "",
        "While you work:",
        "",
        "- Run `karni rules --check <file>` on every file you write and fix each violation it prints.",
        "- Routine tasks are procedures: run `karni rules --procedure <name>` and follow every",
        "  step. A request that starts with `/<name>` asks for that procedure, for the rest of",
        "  the request:",
        *(f"  - `{p['name']}`: {p['description']}" for p in data.procedures),
    ]
    if any(p["name"] == NEW_APP for p in data.procedures):
        lines.append(
            "- To build an app from a one-line request (`/new-app <the request>`), follow the "
            "`new-app` procedure: karni.yaml first, then `karni build` (rule K311)."
        )
    if kind is None:
        lines.append(
            "- App screens go in `frontend/src/pages/` (`karni make page`). A public, "
            "server-rendered website goes in a site app (`karni make site`, rule K309)."
        )
    lines += [
        "- Run `karni check` before committing. Every enforced rule fails the build.",
        "",
        "If the `karni` command is unavailable, say so and stop. Do not guess the conventions.",
    ]
    if note:
        lines += ["", note]
    return lines


def _module_section(fragments: dict[str, str], inline: bool) -> list[str]:
    if not fragments:
        return []
    lines = ["", "## Module guidance", ""]
    if not inline:
        lines += [f"- {name}: run `karni rules` (includes its guidance)" for name in fragments]
        return lines
    for name, fragment in fragments.items():
        lines += [f"<!-- karni:module:{name} -->", fragment, f"<!-- /karni:module:{name} -->", ""]
    return lines[:-1]


def _join(lines: list[str]) -> str:
    return "\n".join(lines).rstrip("\n") + "\n"


def render_adapter(
    adapter: Adapter,
    registry: Registry,
    data: AgentData,
    title: str,
    fragments: dict[str, str],
    kind: ProjectKind | None = None,
) -> str:
    if adapter.template == "import":
        target = next((a for a in registry.adapters if a.id == adapter.imports), None)
        if target is not None:
            rel = Path(target.path)
            return _join([MARKER_LINE, f"@{rel.as_posix()}"])
        # The imported adapter is disabled: fall back to the full body.
    head = _frontmatter(adapter.frontmatter)
    body = head + instructions_body(title, data, adapter.note, kind)
    if not adapter.modules:
        return _join(body)
    full = _join(body + _module_section(fragments, inline=True))
    if full.count("\n") <= registry.max_lines:
        return full
    return _join(body + _module_section(fragments, inline=False))


def render_command(target: CommandTarget, procedure: dict[str, Any]) -> str:
    values: dict[str, Any] = {}
    for key in target.frontmatter:
        if key == "description":
            values[key] = procedure["description"]
        elif key == "argument-hint":
            values[key] = procedure["argument_hint"]
        elif key == "agent":
            values[key] = target.agent
    lines = _frontmatter(values)
    lines.append(procedure["intro"].replace("{arguments}", target.arguments))
    lines.append("")
    lines += [f"{i}. {step}" for i, step in enumerate(procedure["steps"], start=1)]
    if procedure.get("outro"):
        lines += ["", procedure["outro"]]
    if procedure.get("rules"):
        codes = ", ".join(procedure["rules"])
        lines += ["", f"Rules that apply: {codes} (`karni rules --explain <code>`)."]
    lines += ["", MARKER_LINE]
    return _join(lines)


def present(
    project: Path,
    registry: Registry,
    keep: Collection[str] = (),
    original: Registry | None = None,
) -> Registry:
    """``registry`` without the deprecated entries ``project`` does not have.

    A deprecated instruction file counts when a generated file is at its path,
    a deprecated command folder when it holds a generated file. A hand-written
    file in either place is the project's own and does not count. ``keep``
    lists paths that count as present anyway (``karni upgrade`` passes the old
    files it just migrated, so the project keeps its tool's files).
    ``original`` is the registry before karni.rules.py moved paths: a file
    still at its old place counts, so a moved entry is written at the new one.
    """
    kept = {Path(rel).as_posix() for rel in keep}
    before: dict[str, str] = {}
    if original is not None:
        before = {a.id: Path(a.path).as_posix() for a in original.adapters}
        before |= {c.id: Path(c.dir).as_posix() for c in original.commands}

    def has_file(rel: str) -> bool:
        return rel in kept or is_generated(project / rel)

    def has_dir(rel: str) -> bool:
        if any(path.startswith(rel + "/") for path in kept):
            return True
        base = project / rel
        return base.is_dir() and any(p.is_file() and is_generated(p) for p in base.iterdir())

    def has_adapter(adapter: Adapter) -> bool:
        return has_file(Path(adapter.path).as_posix()) or (
            adapter.id in before and has_file(before[adapter.id])
        )

    def has_commands(target: CommandTarget) -> bool:
        return has_dir(Path(target.dir).as_posix()) or (
            target.id in before and has_dir(before[target.id])
        )

    return Registry(
        tuple(a for a in registry.adapters if not a.deprecated or has_adapter(a)),
        tuple(c for c in registry.commands if not c.deprecated or has_commands(c)),
        registry.max_lines,
    )


def deprecated_files(registry: Registry, files: Collection[str]) -> list[str]:
    """The paths in ``files`` that a deprecated entry of ``registry`` writes."""
    paths = {Path(a.path).as_posix() for a in registry.adapters if a.deprecated}
    dirs = tuple(Path(c.dir).as_posix() + "/" for c in registry.commands if c.deprecated)
    return sorted(rel for rel in files if rel in paths or rel.startswith(dirs))


def deprecation_warning(paths: Collection[str]) -> str:
    """The one C860 warning for the deprecated per-tool files a project has."""
    groups: dict[str, list[str]] = {}
    for rel in sorted(paths):
        groups.setdefault(rel.rpartition("/")[0], []).append(rel)
    names: list[str] = []
    for parent, rels in groups.items():
        names += [f"{parent}/ ({len(rels)} files)"] if parent and len(rels) > 1 else rels
    return (
        f"{DEPRECATED_CODE}: these tool-specific agent files are deprecated: "
        f"{', '.join(names)}. Karni still updates them in 0.5. They stop being updated, "
        "and are removed, in 1.0. AGENTS.md is the file to keep: point your tool at it, and "
        "keep project guidance in karni.rules.py (docs/migrations/0.5.md, "
        f"`karni explain {DEPRECATED_CODE}`)."
    )


def render_all(
    project: Path, data: AgentData, registry: Registry | None = None, keep: Collection[str] = ()
) -> dict[str, str]:
    """Every generated file for ``project``: ``{posix relative path: content}``.

    AGENTS.md, and the deprecated per-tool files the project already has
    (:func:`present`).
    """
    base = registry or load_registry()
    registry = present(project, apply_overrides(base, data.adapter_overrides), keep, base)
    title = project_title(project)
    fragments = module_fragments(project)
    kind = project_kind(project)
    files: dict[str, str] = {}
    for adapter in registry.adapters:
        files[Path(adapter.path).as_posix()] = render_adapter(
            adapter, registry, data, title, fragments, kind
        )
    for target in registry.commands:
        for procedure in data.procedures:
            command = Path(target.dir) / f"{procedure['name']}{target.suffix}"
            files[command.as_posix()] = render_command(target, procedure)
    for rel, content in files.items():
        count = content.count("\n")
        if count > registry.max_lines:
            raise CliError(
                f"{rel} would be {count} lines (cap {registry.max_lines}). Shorten the "
                "project rules or module guidance feeding it.",
                code="C205",
            )
    return files


# sync


@dataclass
class SyncResult:
    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    blocked: list[str] = field(default_factory=list)
    backed_up: list[str] = field(default_factory=list)
    #: The deprecated per-tool files kept up to date (C860), whether stale or not.
    deprecated: list[str] = field(default_factory=list)

    @property
    def stale(self) -> list[str]:
        return sorted({*self.written, *self.removed, *self.blocked})


def is_generated(path: Path) -> bool:
    try:
        return GENERATED_MARK in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def _candidates(project: Path, registry: Registry, overrides: dict[str, Any]) -> set[str]:
    """Every place a generated file may have been written (for obsolete cleanup)."""
    paths: dict[str, str] = dict(overrides.get("paths", {}))
    found = {Path(a.path).as_posix() for a in registry.adapters}
    found |= {Path(p).as_posix() for p in paths.values()}
    dirs = {c.dir for c in registry.commands} | set(paths.values())
    for directory in dirs:
        base = project / directory
        if base.is_dir():
            found |= {p.relative_to(project).as_posix() for p in base.iterdir() if p.is_file()}
    return found


def backup(project: Path, rel: str) -> str:
    source = project / rel
    target = project / BACKUP_DIR / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)
    return (BACKUP_DIR / rel).as_posix()


def sync(
    project: Path,
    data: AgentData,
    *,
    check: bool = False,
    force: bool = False,
    keep: Collection[str] = (),
) -> SyncResult:
    """Write (or, with ``check``, only compare) AGENTS.md and the files the project has.

    ``keep``: paths of deprecated per-tool files to write even though the
    project does not have them yet (see :func:`present`).
    """
    registry = load_registry()
    files = render_all(project, data, registry, keep)
    active = apply_overrides(registry, data.adapter_overrides)
    result = SyncResult(deprecated=deprecated_files(active, files))
    for rel, content in sorted(files.items()):
        target = project / rel
        if target.is_file():
            current = target.read_text(encoding="utf-8")
            if current == content:
                result.unchanged.append(rel)
                continue
            if GENERATED_MARK not in current and not force:
                result.blocked.append(rel)
                continue
            if GENERATED_MARK not in current and not check:
                result.backed_up.append(backup(project, rel))
        result.written.append(rel)
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    for rel in sorted(_candidates(project, registry, data.adapter_overrides) - set(files)):
        path = project / rel
        if path.is_file() and is_generated(path):
            result.removed.append(rel)
            if not check:
                path.unlink()
    return result
