"""Render docs/errors.md from every registry — codes and their docs cannot drift.

    python -m karni_cli.errordoc > docs/errors.md

Sources: Karni's registry (``karni.errorcodes``), installed modules'
``karni.errorcodes`` entry points (karni-payments), the CLI's ``C`` codes
(:mod:`karni_cli.errorcodes`), the agent rules (``K`` codes) and the ESLint
plugin's ``rules.json``. ``tests/test_errordoc.py`` fails when the committed
page differs from :func:`render`.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

from karni_cli import agent_data
from karni_cli.errorcodes import CODES as CLI_CODES
from karni_cli.errorcodes import _module_entries, core_module

#: Karni's ranges, in page order: (first code, heading).
RANGES: tuple[tuple[str, str], ...] = (
    ("000", "Models, managers and scopes"),
    ("100", "API: access, viewsets, serializers, pagination, budgets, expand"),
    ("200", "Accounts"),
    ("300", "Admin"),
    ("400", "Events, listeners, schedules and Celery"),
    ("500", "Settings and optional dependencies"),
    ("600", "Testing and seeding"),
    ("700", "Agent tooling: karni check, karni.rules.py, changelog"),
    ("800", "Import and export"),
    ("900", "Debugging: karni queries, karni explain"),
)

INTRO = """\
---
description: Every Karni error code with why it happens and how to fix it, the page each error message links to.
---

# Error codes

<!-- Generated by `python -m karni_cli.errordoc > docs/errors.md`; never edit by hand. -->

Every error Karni raises starts with a code and ends with a link to its entry
on this page:

```text
E104: EventViewSet: Owned('organiser') does not lead from Event to the user model
(Event has no field 'organiser'). Name a relation path ending at the user, e.g.
Owned("organizer") or Owned("event__organizer"). See …/errors/#e104
```

The message names *your* class, field or setting. The entry below says why
Karni objects and how to fix it in general. Offline, without a browser:

```sh
karni explain E104      # any code on this page: E, W, C, PAY, K
```

Codes are permanent: a code never changes meaning and is never reused, so
match on the code, not on the wording, which improves between releases.

| Prefix | Comes from |
|---|---|
| `E` / `W` | Karni itself: exceptions, system checks (`W` = warning), API errors, test failures |
| `PAY` | the karni-payments module (each module has its own prefix) |
| `C` | the `karni` command |
| `K` | agent rules, enforced by `karni check` and the architecture tests |
| `karni/…` | the ESLint plugin shipped with @karni/ui |

System checks run on `runserver`, `migrate`, `check` and every management
command, so problems surface on boot rather than on the first request. Their
ids are `karni.<code>`. Silence a warning on purpose with
`SILENCED_SYSTEM_CHECKS = ["karni.W001"]`. `karni_settings()` starts that list
empty, so `SILENCED_SYSTEM_CHECKS += ["karni.W001"]` works in a project.

End-user outcomes are not on this page: wrong credentials, expired or used
tokens, an invalid 2FA code, a declined payment, a 404 for a row outside your
`access`. Those are ordinary API responses (see [accounts](accounts.md) and
[api](api.md)), not mistakes in your code.
"""

KIND_LABEL: Mapping[str, str] = {
    "exception": "exception",
    "check": "system check (error)",
    "warning": "system check (warning)",
    "api": "API 400 response",
    "test": "test failure",
    "cli": "karni command",
}


def _entry(entry: Mapping[str, str]) -> str:
    code = entry["code"]
    return "\n".join(
        [
            f'<a id="{code.lower()}"></a>',
            "",
            f"### {code}: {entry['title']}",
            "",
            f"*{KIND_LABEL.get(entry['kind'], entry['kind'])}* · from `{entry['source']}`",
            "",
            f"**Why Karni objects.** {entry['why']}",
            "",
            f"**Fix.** {entry['fix']}",
            "",
        ]
    )


def _section(title: str, entries: Iterable[Mapping[str, str]], level: str = "##") -> str:
    body = "\n".join(_entry(entry) for entry in entries)
    return f"{level} {title}\n\n{body}"


def _core_sections(core: Any) -> list[str]:
    entries = sorted((entry.as_dict() for entry in core.CODES), key=lambda e: e["code"][1:])
    sections = ["## Karni (`E`, `W`)\n"]
    for index, (start, title) in enumerate(RANGES):
        end = RANGES[index + 1][0] if index + 1 < len(RANGES) else "999"
        inside = [e for e in entries if start <= e["code"][1:] < end]
        if inside:
            sections.append(_section(f"{start[0]}xx · {title}", inside, level="###"))
    # Within a range the headings are ### too; demote entries to ####.
    return [
        section.replace("\n### E", "\n#### E").replace("\n### W", "\n#### W")
        for section in sections
    ]


def _module_sections() -> list[str]:
    by_prefix: dict[str, list[dict[str, str]]] = {}
    for entry in _module_entries():
        prefix = "".join(ch for ch in entry.code if ch.isalpha())
        by_prefix.setdefault(prefix, []).append(dict(entry.as_dict()))
    names = {"PAY": "karni-payments"}
    return [
        _section(
            f"{names.get(prefix, prefix)} (`{prefix}`)", sorted(items, key=lambda e: e["code"])
        )
        for prefix, items in sorted(by_prefix.items())
    ]


def _rule_section() -> str:
    rules = sorted(agent_data.load(None).rules, key=lambda rule: str(rule["code"]))
    blocks = [
        "\n".join(
            [
                f'<a id="{str(rule["code"]).lower()}"></a>',
                "",
                f"### {rule['code']}: {rule['summary']}",
                "",
                f"*agent rule, {rule['severity']}* · enforced by "
                + ", ".join(f"`{name}`" for name in rule.get("enforced_by") or ["review"]),
                "",
                f"**Rule.** {rule['rule']}",
                "",
                f"**Why Karni objects.** {rule['rationale']}",
                "",
                f"**Fix.** {rule['fix']}",
                "",
            ]
        )
        for rule in rules
    ]
    return (
        "## Agent rules (`K`)\n\n"
        + (
            "`karni rules` lists them in one screen. `karni check` and the architecture tests "
            "(`pytest --pyargs karni.testing.architecture`) enforce them.\n\n"
        )
        + "\n".join(blocks)
    )


def _eslint_manifest() -> list[dict[str, str]]:
    for parent in Path(__file__).resolve().parents:
        candidate = parent / "packages" / "karni-ui" / "eslint-plugin" / "rules.json"
        if candidate.is_file():
            data = json.loads(candidate.read_text(encoding="utf-8"))
            return [dict(item) for item in data]
    return []


def _eslint_section() -> str:
    blocks = [
        "\n".join(
            [
                f'<a id="{item["id"].replace("/", "-")}"></a>',
                "",
                f"### `{item['id']}`: {item['title']}",
                "",
                f"**Why Karni objects.** {item['why']}",
                "",
                f"**Fix.** {item['fix']}",
                "",
            ]
        )
        for item in _eslint_manifest()
    ]
    return (
        "## ESLint rules (`@karni/ui/eslint-plugin`)\n\n"
        + (
            "Every rule is an error in `karni.configs.recommended`. An opt-out needs an "
            "`eslint-disable` comment with a `-- reason`.\n\n"
        )
        + "\n".join(blocks)
    )


def render() -> str:
    core = core_module()
    if core is None:  # pragma: no cover - the monorepo always has the source
        raise SystemExit("karni/errorcodes not found")
    parts = [
        INTRO,
        *_core_sections(core),
        *_module_sections(),
        _section("The karni command (`C`)", [code.as_dict() for code in CLI_CODES]),
        _rule_section(),
        _eslint_section(),
    ]
    return "\n".join(part.rstrip("\n") + "\n" for part in parts)


if __name__ == "__main__":
    print(render(), end="")
