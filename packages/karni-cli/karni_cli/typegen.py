"""Typed-hook generation for ``karni types`` (E2).

The item component for each resource is resolved by following the list
operation's 200 response ``$ref`` through the paginated wrapper to
``properties.results.items.$ref`` — never derived from the resource name
(component names are app-qualified, e.g. ``TestappEvent``).

A resource whose aggregate operation carries ``x-karni-aggregate``
(experimental) also gets ``use<Resource>Aggregate``, whose ``groupBy`` is
the union of the groups it declares.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from karni_cli.project import CliError

HEADER = "// Generated by karni types. Do not edit.\n"


def load_schema(path: Path) -> dict[str, Any]:
    text = path.read_text()
    if path.suffix == ".json":
        return json.loads(text)
    return yaml.safe_load(text)


def _resolve(doc: dict[str, Any], ref: str) -> dict[str, Any]:
    if not ref.startswith("#/"):
        raise CliError(f"Unsupported external $ref: {ref}", code="C206")
    node: Any = doc
    for part in ref[2:].split("/"):
        node = node[part]
    return node


def _component_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def resource_components(doc: dict[str, Any]) -> dict[str, str]:
    """resource → item component name, from list ops carrying x-karni-resource."""
    out: dict[str, str] = {}
    for _path, item in sorted(doc.get("paths", {}).items()):
        op = item.get("get")
        if not op:
            continue
        resource = op.get("x-karni-resource")
        if not resource or resource in out:
            continue
        try:
            ref = op["responses"]["200"]["content"]["application/json"]["schema"]["$ref"]
            paginated = _resolve(doc, ref)
            items_ref = paginated["properties"]["results"]["items"]["$ref"]
        except (KeyError, TypeError):
            continue  # not a paginated list response; skip quietly
        out[resource] = _component_name(items_ref)
    return out


def aggregate_groups(doc: dict[str, Any]) -> dict[str, list[str]]:
    """resource -> the groups its aggregate action takes (``x-karni-aggregate``), experimental.

    The aggregate operation sits at ``<list path>aggregate/``. A resource
    without a declared aggregation has no such operation.
    """
    found: dict[str, list[str]] = {}
    paths = doc.get("paths", {})
    for path, item in sorted(paths.items()):
        resource = (item.get("get") or {}).get("x-karni-resource")
        if not resource or resource in found:
            continue
        operation = (paths.get(f"{path}aggregate/") or {}).get("get") or {}
        declared = operation.get("x-karni-aggregate")
        if isinstance(declared, dict):
            found[resource] = [str(group) for group in declared.get("group_by") or []]
    return found


def _pascal(resource: str) -> str:
    return "".join(part.capitalize() for part in resource.replace("-", "_").split("_"))


def generate_hooks(doc: dict[str, Any]) -> str:
    resources = resource_components(doc)
    if not resources:
        raise CliError("No x-karni-resource list operations found in the schema.", code="C206")
    aggregates = {name: groups for name, groups in aggregate_groups(doc).items() if groups}
    hooks = ["useResourceItem", "useResourceList", "useResourceMutations"]
    types = ["ResourceItemParams", "ResourceListParams", "ResourceMutationsOptions"]
    if aggregates:
        hooks.insert(0, "useAggregate")
        types.insert(0, "AggregateParams")
    lines = [
        HEADER.rstrip("\n"),
        f'import {{ {", ".join(hooks)} }} from "@karni/ui";',
        "import type {",
        *(f"  {name}," for name in types),
        '} from "@karni/ui";',
        'import type { components } from "./types";',
        "",
    ]
    for resource, component in sorted(resources.items()):
        name = _pascal(resource)
        item = f'components["schemas"]["{component}"]'
        lines += [
            f"export type {name}Item = {item};",
            f"export const use{name}List = (params?: ResourceListParams) =>",
            f'  useResourceList<{item}>("{resource}", params);',
            f"export const use{name}Item = (id: string | number, params?: ResourceItemParams) =>",
            f'  useResourceItem<{item}>("{resource}", id, params);',
            f"export const use{name}Mutations = (options?: ResourceMutationsOptions) =>",
            f'  useResourceMutations<{item}>("{resource}", options);',
            "",
        ]
        groups = aggregates.get(resource)
        if groups:
            union = " | ".join(json.dumps(group) for group in groups)
            lines += [
                f"export type {name}AggregateGroup = {union};",
                f"export const use{name}Aggregate = (",
                f"  params: AggregateParams & {{ groupBy: {name}AggregateGroup }},",
                f') => useAggregate("{resource}", params);',
                "",
            ]
    return "\n".join(lines)


def write_hooks(schema_path: Path, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    hooks = out_dir / "hooks.ts"
    hooks.write_text(generate_hooks(load_schema(schema_path)))
    return hooks
