from __future__ import annotations

import json
from pathlib import Path

import pytest

from karni_cli.project import CliError
from karni_cli.typegen import generate_hooks, resource_components

FIXTURE = Path(__file__).parent / "fixtures" / "schema.fixture.json"


@pytest.fixture
def schema() -> dict:
    return json.loads(FIXTURE.read_text())


def test_item_component_resolved_via_pagination_ref(schema: dict) -> None:
    assert resource_components(schema) == {
        "events": "TestappEvent",
        "venues": "TestappVenue",
    }


def test_generated_hooks_golden(schema: dict) -> None:
    out = generate_hooks(schema)
    assert out.startswith("// generated by karni types — do not edit")
    # app-qualified component name, never derived from the resource string
    assert 'useResourceList<components["schemas"]["TestappEvent"]>("events", params)' in out
    assert 'useResourceItem<components["schemas"]["TestappVenue"]>("venues", id, params)' in out
    assert "export const useEventsList" in out
    assert "export const useVenuesMutations" in out
    assert 'from "@karni/ui"' in out and 'from "./types"' in out
    # deterministic: events before venues
    assert out.index("useEventsList") < out.index("useVenuesList")


def test_no_karni_resources_errors(schema: dict) -> None:
    for item in schema["paths"].values():
        item["get"].pop("x-karni-resource", None)
    with pytest.raises(CliError, match="x-karni-resource"):
        generate_hooks(schema)


def test_detail_op_without_pagination_is_skipped(schema: dict) -> None:
    # the detail path has no x-karni-resource and a non-paginated response: ignored
    assert "events" in resource_components(schema)
