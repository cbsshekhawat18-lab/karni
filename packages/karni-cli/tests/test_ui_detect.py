def test_css_reader() -> None:
    sheet = css.parse(
        """
        /* :root { --ignored: 1 } */
        @import "./theme.css";
        @layer base {
          :root { --a: 1px; --b: "x;y"; color: red; }
          .dark, [data-theme=dark] { --a: 2px; }
        }
        @media (min-width: 1px) { :root { --c: calc(1px + 2px); } }
        @keyframes spin { from { --nope: 1; } }
        @theme inline { --color-x: var(--x); }
        """
    )
    assert sheet.imports == ["./theme.css"]
    assert sheet.variables(":root") == {"--a": "1px", "--b": '"x;y"', "--c": "calc(1px + 2px)"}
    assert sheet.variables(".dark") == {"--a": "2px"}
    assert sheet.theme() == {"--color-x": "var(--x)"}
    assert css.is_hsl_channels("222.2 47.4% 11.2%")
    assert not css.is_hsl_channels("oklch(0.2 0.1 250)")


def test_js_object_reader() -> None:
    source = """
    const brand = ["#000", "#111"];
    const palette = {
      primary: { main: '#123', "contrast-text": `#fff`, },  // comment
      list: [1, 2.5, -3],
      flag: true,
      size: 8 as const,
      computed: alpha(brand, 0.5),
      member: colors.blue[500],
      template: `${x}px`,
      arrow: (theme) => theme.spacing(2),
      method() { return 1 },
      brand,
      ...rest,
    };
    """
    tree = jsobject.parse_value(source, jsobject.resolve_identifier(source, "palette") or 0)
    assert tree["primary"] == {"main": "#123", "contrast-text": "#fff"}
    assert tree["list"] == [1, 2.5, -3]
    assert tree["flag"] is True and tree["size"] == 8
    assert tree["brand"] == ["#000", "#111"]  # a const in the same file is read
    kinds = {k: v.kind for k, v in tree.items() if isinstance(v, NonLiteral)}
    assert kinds == {
        "computed": "call",
        "member": "variable",
        "template": "template",
        "arrow": "function",
        "method": "expression",
        "...0": "spread",
    }


