def test_rerun_overwrites_an_untouched_file_and_refuses_an_edited_one(tmp_path: Path) -> None:
    root = project(tmp_path, "shadcn-tw3")
    theme = root / "src" / "karni-theme.css"
    ok("--frontend", str(root))
    first = theme.read_text()
    second = ok("--frontend", str(root))
    assert "unchanged: src/karni-theme.css" in second.output
    assert "ok: src/main.tsx already imports karni-theme.css" in second.output
    assert "ok: src/App.tsx already passes primitives" in second.output
    assert theme.read_text() == first
    main = (root / "src" / "main.tsx").read_text()
    assert main.count("karni-theme.css") == 1

    theme.write_text(first.replace("hsl(var(--primary))", "#7c3aed"))
    assert render.state(theme) == "modified"
    message = fails("--frontend", str(root), code="C302")
    assert "src/karni-theme.css was edited" in message and "--force" in message
    assert "#7c3aed" in theme.read_text()  # nothing written

    ok("--frontend", str(root), "--force")
    assert theme.read_text() == first


