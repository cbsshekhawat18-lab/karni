FIXTURES = Path(__file__).parent / "fixtures" / "ui"


def project(tmp_path: Path, name: str) -> Path:
    target = tmp_path / name
    shutil.copytree(FIXTURES / name, target)
    return target


def run(*args: str) -> Result:
    return CliRunner().invoke(app, ["ui", "detect", *args])


def ok(*args: str) -> Result:
    result = run(*args)
    assert result.exit_code == 0, f"{args}: {result.output}\n{result.exception!r}"
    return result


def fails(*args: str, code: str) -> str:
    result = run(*args)
    assert result.exit_code != 0, result.output
    message = str(result.exception) if result.exception else result.output
    assert message.startswith(f"{code}:"), message
    return message


def report(root: Path, *args: str) -> dict[str, Any]:
    data = json.loads(ok("--frontend", str(root), "--json", *args).output)
    assert isinstance(data, dict)
    return data


def mapped(data: dict[str, Any]) -> dict[tuple[str, str], str]:
    """(token, scheme) -> value."""
    return {(m["to"], m["scheme"]): m["value"] for m in data["mapped"]}


def not_mapped(data: dict[str, Any]) -> dict[str, dict[str, str]]:
    return {u["name"]: u for u in data["not_mapped"]}


