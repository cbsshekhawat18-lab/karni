"""``karni ui detect``: each detection case on a fixture project, the files it writes, the guard.

The fixture projects live in tests/fixtures/ui/ and are copied to a temporary
directory per test. The Tailwind 3 config test evaluates a real
tailwind.config.ts with Node and tailwindcss 3: it runs when
``KARNI_TEST_TAILWIND3`` names a node_modules directory holding tailwindcss 3
(CI installs one); without it the test is skipped and says so.
"""

