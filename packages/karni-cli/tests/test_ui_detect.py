def test_tailwind4_theme_blocks(tmp_path: Path) -> None:
    root = project(tmp_path, "tailwind4")
    data = report(root)
    assert data["source"] == "tailwind"
    assert data["detected"] == "Tailwind 4 theme (@theme in src/theme.css)"
    tokens = mapped(data)
    # Each token reads the theme variable (live, .dark overrides included), value as fallback.
    assert tokens[("--karni-color-primary", "both")] == (
        "var(--color-primary, oklch(0.55 0.22 285))"
    )
    assert tokens[("--karni-color-destructive", "both")] == "var(--color-danger, #dc2626)"
    assert tokens[("--karni-space-unit", "both")] == "var(--spacing, 0.3rem)"
    assert tokens[("--karni-radius-lg", "both")] == "var(--radius-lg, 0.75rem)"
    assert tokens[("--karni-font-leading-sm", "both")] == ("var(--text-sm--line-height, 1.25rem)")
    unmapped = not_mapped(data)
    palette = unmapped["@theme --color-brand-* (5 shades)"]
    assert "Karni does not guess that it is your primary colour" in palette["reason"]
    assert palette["suggestion"] == "--karni-color-primary: #4f46e5;"
    assert unmapped["@theme --breakpoint-3xl"]["reason"] == "Karni has no breakpoint tokens"
    assert "@theme --color-surface" in unmapped
    # The palette is not turned into primary silently; its line is offered in the file.
    theme = (root / "src" / "karni-theme.css").read_text()
    assert "--karni-color-primary: #4f46e5" not in theme.split("/* Not mapped")[0]
    assert "@theme --color-brand-* (5 shades): --karni-color-primary: #4f46e5;" in theme


def _tailwind3_modules() -> Path | None:
    configured = os.environ.get("KARNI_TEST_TAILWIND3")
    if not configured:
        return None
    modules = Path(configured)
    manifest = modules / "tailwindcss" / "package.json"
    assert manifest.is_file(), f"KARNI_TEST_TAILWIND3={configured} has no tailwindcss"
    assert json.loads(manifest.read_text())["version"].startswith("3."), "needs tailwindcss 3"
    return modules


@pytest.mark.skipif(
    not os.environ.get("KARNI_TEST_TAILWIND3") or shutil.which("node") is None,
    reason="needs Node and tailwindcss 3: set KARNI_TEST_TAILWIND3 to a node_modules holding "
    "tailwindcss@3 (npm install --prefix <dir> tailwindcss@3); CI sets it",
)
def test_tailwind3_config_is_evaluated_and_diffed_against_the_defaults(tmp_path: Path) -> None:
    modules = _tailwind3_modules()
    assert modules is not None
    root = project(tmp_path, "tailwind3")
    (root / "node_modules").symlink_to(modules.resolve(), target_is_directory=True)
    data = report(root)
    assert data["source"] == "tailwind"
    assert data["detected"].startswith("Tailwind 3 theme (tailwind.config.ts, tailwindcss 3.")
    tokens = mapped(data)
    assert tokens[("--karni-color-primary", "light")] == "#7c3aed"
    assert tokens[("--karni-color-primary-foreground", "light")] == "#ffffff"
    # danger means destructive; <alpha-value> is dropped.
    assert tokens[("--karni-color-destructive", "light")] == "rgb(220 38 38)"
    # A value that reads a variable is declared on :root and .dark.
    assert tokens[("--karni-color-background", "both")] == "hsl(var(--app-bg))"
    assert tokens[("--karni-font-sans", "light")].startswith("Inter, ui-sans-serif")
    assert tokens[("--karni-radius-lg", "light")] == "0.875rem"
    assert tokens[("--karni-shadow-md", "light")] == "0 4px 12px rgb(0 0 0 / 0.08)"
    # Only the project's own values: Tailwind's defaults (gray, sm radius, ...) are not mapped.
    assert all(not name.startswith("theme.colors.gray") for name in not_mapped(data))
    unmapped = not_mapped(data)
    assert unmapped["theme.colors.brand"]["suggestion"] == "--karni-color-primary: #4f46e5;"
    assert "derives -hover" in unmapped["theme.colors.primary.hover"]["reason"]
    assert "theme.screens" in unmapped and "theme.fontFamily.display" in unmapped


