    theme = (root / "src" / "karni-theme.css").read_text()
    # One block on :root and .dark, so a dark subtree recomputes the references.
    assert ":root,\n.dark {\n" in theme
    assert "  --karni-color-primary: hsl(var(--primary));\n" in theme
    assert "Detected: shadcn/ui" in theme and "Read: components.json, src/index.css" in theme
    assert re.search(r"Generated by `karni ui detect` on \d{4}-\d{2}-\d{2}\.", theme)
    assert "This file is yours" in theme
    assert render.state(root / "src" / "karni-theme.css") == "unmodified"

    # The scaffold's main.tsx gets the import right after @karni/ui/styles.css.
    main = (root / "src" / "main.tsx").read_text()
    assert main.startswith('import "@karni/ui/styles.css";\nimport "./karni-theme.css";\n')


