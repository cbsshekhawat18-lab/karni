"""Roles as data (ADR 0002, P1): Role / Permission / RolePermission tables.

Schema generated by Django; the data step at the end gives every existing
auth ``Group`` a ``Role`` row (slug from the group name), so projects that
used ``assign_role`` before 0.2 keep their roles — ``karni sync-roles`` then
fills the grants ``KARNI_ROLES`` declares. Nothing is deleted on reverse: the
``Role`` rows go with the tables, the groups stay.
"""

import django.db.models.deletion
