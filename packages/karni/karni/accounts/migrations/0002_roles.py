from django.utils.text import slugify


def roles_for_existing_groups(apps, schema_editor):
    """One ``Role`` per ``Group`` that has none; the slug is unique by construction."""
    Group = apps.get_model("auth", "Group")
    Role = apps.get_model("karni_accounts", "Role")
    taken = set(Role.objects.values_list("slug", flat=True))
    for group in Group.objects.filter(karni_role__isnull=True).order_by("name"):
        base = slugify(group.name) or f"group-{group.pk}"
        slug, n = base, 2
        while slug in taken:
            slug, n = f"{base}-{n}", n + 1
        taken.add(slug)
        Role.objects.create(group=group, slug=slug, name=group.name)


