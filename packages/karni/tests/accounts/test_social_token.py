def test_the_default_fetcher_is_https_only_and_parses_json(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    with pytest.raises(KarniValueError, match="https"):
        fetch_jwks("http://insecure.example.test/jwks")
    seen: dict[str, Any] = {}

    def fake_urlopen(request: Any, timeout: float) -> Any:
        seen.update(url=request.full_url, timeout=timeout)
        return io.BytesIO(json.dumps({"keys": []}).encode())

    monkeypatch.setattr(social_token.urllib.request, "urlopen", fake_urlopen)
    assert fetch_jwks("https://idp.example.test/jwks") == {"keys": []}
    assert seen == {"url": "https://idp.example.test/jwks", "timeout": 5.0}


