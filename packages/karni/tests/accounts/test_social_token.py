def test_hmac_and_none_algorithms_are_refused(client: APIClient) -> None:
    import jwt

    claims = idtokens.claims_for("google")
    hmac_token = jwt.encode(
        claims, "a-shared-secret-of-at-least-32-bytes", algorithm="HS256", headers={"kid": "rsa-1"}
    )
    assert_refused(post(client, "google", hmac_token), "E215", 401)
    unsigned = jwt.encode(claims, "", algorithm="none", headers={"kid": "rsa-1"})
    assert_refused(post(client, "google", unsigned), "E215", 401)
    # An RS256 provider refuses an ES256 token even from a key it would know.
    idtokens.serve(GoogleProvider.jwks_url, "rsa-1", "ec-1")
    assert_refused(post(client, "google", mint("google", kid="ec-1")), "E215", 401)


