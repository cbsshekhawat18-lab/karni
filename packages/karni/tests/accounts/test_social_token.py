def test_unknown_kid_fetches_again_then_refuses_and_waits_a_minute(client: APIClient) -> None:
    assert_signed_in(post(client, "google", mint("google")))  # caches rsa-1
    assert_refused(post(client, "google", mint("google", kid="rsa-2")), "E219", 401)
    assert FETCHES[GoogleProvider.jwks_url] == 2
    # Within the minute another unknown kid does not fetch again.
    assert_refused(post(client, "google", mint("google", kid="rsa-other")), "E219", 401)
    assert FETCHES[GoogleProvider.jwks_url] == 2


def test_a_rotated_key_is_fetched_and_accepted(client: APIClient) -> None:
    assert_signed_in(post(client, "google", mint("google")))  # caches rsa-1
    idtokens.serve(GoogleProvider.jwks_url, "rsa-1", "rsa-2")  # the provider rotates
    assert_signed_in(post(client, "google", mint("google", kid="rsa-2")))
    assert FETCHES[GoogleProvider.jwks_url] == 2
    # The new set is cached: the old key still works without a fetch.
    assert_signed_in(post(client, "google", mint("google")))
    assert FETCHES[GoogleProvider.jwks_url] == 2


