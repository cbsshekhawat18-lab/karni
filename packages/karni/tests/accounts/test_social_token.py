def test_a_racing_first_sign_in_resolves_to_the_same_account(
    monkeypatch: pytest.MonkeyPatch, client: APIClient
) -> None:
    calls = {"n": 0}
    original = social_token._create

    def racing_create(*args: Any, **kwargs: Any) -> Any:
        calls["n"] += 1
        if calls["n"] == 1:
            original(*args, **kwargs)  # the other request wins the race
            raise IntegrityError("duplicate key")
        return original(*args, **kwargs)

    monkeypatch.setattr(social_token, "_create", racing_create)
    assert_signed_in(post(client, "google", mint("google")))
    assert users().filter(email="ada@example.com").count() == 1


